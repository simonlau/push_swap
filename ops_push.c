#include "push_swap.h"
#include "libft/libft.h"
#include <unistd.h>

void	pa(t_stack *a, t_stack *b)
{
	int				value;
	unsigned int	i;

	if (!a || !b || b->size == 0)
		return ;
	value = b->data[0];
	i = 0;
	while (i < b->size - 1)
	{
		b->data[i] = b->data[i + 1];
		i++;
	}
	b->size--;
	i = a->size;
	while (i > 0)
	{
		a->data[i] = a->data[i - 1];
		i--;
	}
	a->data[0] = value;
	a->size++;
	ft_putstr_fd("pa\n", STDOUT_FILENO);
}

void	pb(t_stack *a, t_stack *b)
{
	int				value;
	unsigned int	i;

	if (!a || !b || a->size == 0)
		return ;
	value = a->data[0];
	i = 0;
	while (i < a->size - 1)
	{
		a->data[i] = a->data[i + 1];
		i++;
	}
	a->size--;
	i = b->size;
	while (i > 0)
	{
		b->data[i] = b->data[i - 1];
		i--;
	}
	b->data[0] = value;
	b->size++;
	ft_putstr_fd("pb\n", STDOUT_FILENO);
}
